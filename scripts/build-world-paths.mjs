// Convert the topojson world-atlas (countries-110m) into a self-contained
// TypeScript module of pre-projected SVG path strings. Air-gapped friendly:
// the output bakes the geometry into JS so the production bundle never needs
// to fetch the topojson at runtime.
//
// Run once (or whenever you want a new resolution):
//   node scripts/build-world-paths.mjs <topojson-path> <output-ts-path>
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [,, inPath, outPath] = process.argv;
if (!inPath || !outPath) {
  console.error('Usage: node build-world-paths.mjs <input.json> <output.ts>');
  process.exit(2);
}

const topo = JSON.parse(readFileSync(resolve(inPath), 'utf-8'));

// --- topojson arc decoding ------------------------------------------------
// The arcs are delta-encoded: arc[i].x = arc[i-1].x + delta. After decoding,
// every point is transformed by topo.transform.scale + topo.transform.translate
// to get back to (longitude, latitude).
const { scale, translate } = topo.transform;
const decodedArcs = topo.arcs.map(arc => {
  let x = 0, y = 0;
  const pts = [];
  for (const [dx, dy] of arc) {
    x += dx; y += dy;
    pts.push([x * scale[0] + translate[0], y * scale[1] + translate[1]]);
  }
  return pts;
});

// --- equirectangular projection on a 1000x500 canvas ----------------------
const W = 1000, H = 500;
function project([lon, lat]) {
  const x = ((lon + 180) / 360) * W;
  const y = ((90 - lat) / 180) * H;
  return [x, y];
}

// --- pixel-level Douglas-Peucker simplification ---------------------------
// We project FIRST, then simplify in pixel space - simpler to control the
// on-screen detail level than running it on raw geographic coords.
function perpDist(p, a, b) {
  const [px, py] = p, [ax, ay] = a, [bx, by] = b;
  const dx = bx - ax, dy = by - ay;
  if (dx === 0 && dy === 0) return Math.hypot(px - ax, py - ay);
  const t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy);
  const cx = ax + t * dx, cy = ay + t * dy;
  return Math.hypot(px - cx, py - cy);
}
function simplify(points, eps) {
  if (points.length < 3) return points.slice();
  const stack = [[0, points.length - 1]];
  const keep = new Array(points.length).fill(false);
  keep[0] = keep[points.length - 1] = true;
  while (stack.length) {
    const [s, e] = stack.pop();
    let maxD = 0, idx = -1;
    for (let i = s + 1; i < e; i++) {
      const d = perpDist(points[i], points[s], points[e]);
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > eps && idx !== -1) {
      keep[idx] = true;
      stack.push([s, idx], [idx, e]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function ringToPath(arcIdxs) {
  const ring = [];
  for (const i of arcIdxs) {
    const reverse = i < 0;
    const arc = decodedArcs[reverse ? ~i : i];
    const seg = reverse ? arc.slice().reverse() : arc;
    // first point on subsequent arcs is the same as previous arc's last -> skip duplicate
    if (ring.length === 0) ring.push(...seg);
    else ring.push(...seg.slice(1));
  }
  // project
  const proj = ring.map(project);
  // simplify in pixel space (0.4px tolerance keeps things crisp without bloat)
  const simp = simplify(proj, 0.4);
  if (simp.length < 3) return null;
  const head = `M${simp[0][0].toFixed(1)},${simp[0][1].toFixed(1)}`;
  const tail = simp.slice(1).map(p => `L${p[0].toFixed(1)},${p[1].toFixed(1)}`).join('');
  return head + tail + 'Z';
}

function geometryToPaths(geom) {
  if (geom.type === 'Polygon') {
    return geom.arcs.map(ringToPath).filter(Boolean);
  }
  if (geom.type === 'MultiPolygon') {
    return geom.arcs.flatMap(polygon => polygon.map(ringToPath).filter(Boolean));
  }
  return [];
}

// --- emit -----------------------------------------------------------------
const entries = [];
for (const g of topo.objects.countries.geometries) {
  const name = g.properties?.name;
  if (!name) continue;
  const paths = geometryToPaths(g);
  if (paths.length === 0) continue;
  entries.push({ name, paths });
}
entries.sort((a, b) => a.name.localeCompare(b.name));

const header = `// AUTO-GENERATED by scripts/build-world-paths.mjs - DO NOT EDIT BY HAND.
// Source: world-atlas/countries-110m.json (public domain, Natural Earth).
// Projection: equirectangular onto a ${W}x${H} SVG canvas.
// Each country is a list of SVG path strings; multi-polygon countries (USA,
// Russia, Indonesia, ...) have one entry per landmass so we can colour them
// individually if we ever want to.
export const WORLD_CANVAS = { width: ${W}, height: ${H} } as const;

export interface CountryShape { name: string; paths: string[] }

export const COUNTRY_SHAPES: ReadonlyArray<CountryShape> = [
`;

const body = entries.map(e =>
  `  { name: ${JSON.stringify(e.name)}, paths: [${e.paths.map(p => JSON.stringify(p)).join(', ')}] }`
).join(',\n');

writeFileSync(resolve(outPath), header + body + '\n];\n', 'utf-8');

const totalChars = entries.reduce((s, e) => s + e.paths.reduce((ss, p) => ss + p.length, 0), 0);
console.log(`  countries:    ${entries.length}`);
console.log(`  output:       ${outPath}`);
console.log(`  total chars:  ${totalChars}`);
console.log(`  avg per ctry: ${Math.round(totalChars / entries.length)}`);
